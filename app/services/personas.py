@dataclass(frozen=True)
class Persona:
    name: str
    vocabulary: str
    rhythm: str
    tone: str
    focus: str
    emotion: str
    examples: str
    opening: str
    transition: str
    ending: str
    judgment: str

    def instruction(self) -> str:
        labels = ["作者视角", "词汇", "句长节奏", "语气口语程度", "观察重点", "情绪强度", "举例与生活经验", "开头", "转折", "结尾", "判断方式"]
        return "\n".join(f"{label}：{value}" for label, value in zip(labels, asdict(self).values()))


